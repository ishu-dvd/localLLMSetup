@dataclass(frozen=True)
class ClientProfile:
    """How to *get* a coding agent, not just how to configure one.

    `join` writes a config file, which is necessary and not sufficient: on a
    fresh laptop the agent it configures is not installed, and the two things
    that actually go wrong - no Node, no VS Code - surface as errors from the
    agent's own installer that mention nothing about this project.
    """

    name: str
    title: str
    install: str
    why: str
    requires: tuple[str, ...] = ()
    """Commands that must already be on PATH. Checked before anything is written."""

    join_name: str = ""
    """The config writer to use, when it differs from `name`."""

    writes_config: bool = True
    """False when the agent keeps its settings somewhere unwritable, so what
    `join` produces is instructions rather than configuration. Stated on the
    profile so the caller can say which it got."""

    free: bool = True

    def __post_init__(self) -> None:
        if not self.join_name:
            object.__setattr__(self, "join_name", self.name)


