            "{",
            "  models: [",
            "    {",
            f'      nickname: "{model} (localllm)",',
            f'      baseUrl: "{origin}",',
            '      apiEnvVar: "LOCAL_LLM_KEY",',
            f'      model: "{model}",',
            f"      context: {context},",
            "    },",
            "  ],",
            "}",
            "",
